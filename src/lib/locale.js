let currentLocale =
  typeof window !== "undefined" &&
  supportedLocales.has(window.localStorage.getItem("kuro-locale"))
    ? window.localStorage.getItem("kuro-locale")
    : "en";

function subscribe(callback) {
  if (typeof window === "undefined") {
    return () => {};
  }

  window.addEventListener("kuro-locale-change", callback);
  return () => window.removeEventListener("kuro-locale-change", callback);
}

function getSnapshot() {
  return currentLocale;
}

function getServerSnapshot() {
  return "en";
}

export function useLocale() {
  return useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);
}

export function setLocale(locale) {
  if (!supportedLocales.has(locale)) {
    return;
  }

  currentLocale = locale;
  if (typeof window !== "undefined") {
    window.localStorage.setItem("kuro-locale", locale);
    document.documentElement.lang = locale === "fil" ? "fil" : locale === "ceb" ? "ceb" : "en";
    window.dispatchEvent(new Event("kuro-locale-change"));
  }
}

export function translate(locale, text) {
  return translations[locale]?.[text] || text;
}
